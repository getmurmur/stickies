// The sticky-note theme, once: scripts/registry.mjs writes it into registry.json (for
// `stickies-theme`) and into theme.css (for this site). Colours from Murmur.

/** Paper, header, edge, ink and meta (the quiet ink for dates) for each colour, light and dark. */
const COLORS = {
  yellow: { light: ["#fdf6c8", "#f6e9a6", "#e8d995", "#3b3214", "#9a8d5c"], dark: ["#48421f", "#575027", "#665d2f", "#f7f0cb", "#b9ad7a"] },
  blue: { light: ["#ddedfb", "#c7dff6", "#abc9ea", "#1d3049", "#6c86a5"], dark: ["#1f3249", "#273d57", "#324b68", "#dcebfb", "#8ea8c7"] },
  green: { light: ["#def3d7", "#c8e9bd", "#a9d69c", "#22391c", "#6e8e65"], dark: ["#223a20", "#2a4727", "#355630", "#ddf2d6", "#90b087"] },
  pink: { light: ["#fbe1ed", "#f5c9dd", "#e7abc6", "#4a1f31", "#a06e85"], dark: ["#48222f", "#572a39", "#683446", "#fbe0ec", "#c493a8"] },
  purple: { light: ["#ede3fb", "#ddcdf6", "#c5aee9", "#33204d", "#8973a7"], dark: ["#34234d", "#3f2b5c", "#4c366d", "#ece2fb", "#a996c6"] },
  grey: { light: ["#f2f2f1", "#e3e3e1", "#cfcfcc", "#2b2b2a", "#8a8a87"], dark: ["#2d2d2c", "#363635", "#434341", "#f0f0ee", "#9d9d9a"] },
}

const PARTS = ["paper", "header", "edge", "ink", "meta"]

const vars = (values) => Object.fromEntries(PARTS.map((part, i) => [`--sticky-${part}`, values[i]]))

/** `[data-sticky-color]` is yellow; each other colour overrides it. Dark follows shadcn's `.dark`. */
function colorRules() {
  const rules = {}
  for (const mode of ["light", "dark"]) {
    const prefix = mode === "dark" ? ".dark " : ""
    rules[`${prefix}[data-sticky-color]`] = vars(COLORS.yellow[mode])
    for (const [name, values] of Object.entries(COLORS)) {
      if (name !== "yellow") rules[`${prefix}[data-sticky-color="${name}"]`] = vars(values[mode])
    }
  }
  return rules
}

const mix = (color, amount) => `color-mix(in oklch, ${color} ${amount}%, transparent)`
const shade = (amount) => mix("var(--sticky-shade)", amount)
const black = (amount) => mix("black", amount)
const white = (amount) => mix("white", amount)

/** Paper on a desk: a tight contact shadow, then softer falloff tinted by the note's ink. Lifted while carried. */
const shadow = {
  "--sticky-shade": "color-mix(in oklch, var(--sticky-ink) 55%, black)",
  "box-shadow": [
    `inset 0 1px 0 ${white(50)}`,
    `0 0 0 0.5px ${shade(6)}`,
    `0 1px 1px ${shade(8)}`,
    `0 3px 6px -2px ${shade(8)}`,
    `0 10px 20px -8px ${shade(12)}`,
    `0 24px 44px -20px ${shade(16)}`,
  ].join(", "),
  transition: "box-shadow 200ms cubic-bezier(0.23, 1, 0.32, 1), translate 200ms cubic-bezier(0.23, 1, 0.32, 1)",
  "&[data-lifted]": {
    translate: "0 -2px",
    "box-shadow": [
      `inset 0 1px 0 ${white(50)}`,
      `0 0 0 0.5px ${shade(6)}`,
      `0 2px 3px ${shade(6)}`,
      `0 8px 14px -4px ${shade(10)}`,
      `0 22px 36px -10px ${shade(16)}`,
      `0 44px 72px -24px ${shade(20)}`,
    ].join(", "),
  },
  ".dark &": {
    "box-shadow": [`inset 0 1px 0 ${white(10)}`, `0 0 0 0.5px ${black(40)}`, `0 1px 2px ${black(30)}`, `0 6px 12px -4px ${black(35)}`, `0 20px 40px -16px ${black(45)}`].join(", "),
  },
  ".dark &[data-lifted]": {
    "box-shadow": [`inset 0 1px 0 ${white(10)}`, `0 0 0 0.5px ${black(40)}`, `0 3px 6px ${black(30)}`, `0 14px 28px -8px ${black(40)}`, `0 40px 72px -24px ${black(55)}`].join(", "),
  },
}

export const themeCssVars = {
  theme: Object.fromEntries(PARTS.map((part) => [`color-sticky-${part}`, `var(--sticky-${part})`])),
}

export const themeCss = {
  "@layer base": colorRules(),
  "@utility sticky-shadow": shadow,
}

/** The same theme as a stylesheet, for a project that imports it rather than installing. */
export function themeStylesheet() {
  const block = (selector, body, indent = "") => {
    const inner = Object.entries(body)
      .map(([key, value]) => (typeof value === "object" ? block(key, value, `${indent}  `) : `${indent}  ${key}: ${value};`))
      .join("\n")
    return `${indent}${selector} {\n${inner}\n${indent}}`
  }
  const header = "/* Generated by scripts/registry.mjs from registry/stickies/theme.mjs. Don't edit. */"
  const theme = block("@theme inline", Object.fromEntries(Object.entries(themeCssVars.theme).map(([k, v]) => [`--${k}`, v])))
  const rules = Object.entries(themeCss).map(([at, body]) => block(at, body))
  return `${header}\n\n${[theme, ...rules].join("\n\n")}\n`
}
